// UK Civil Service Success Profiles strengths-based interview format — verified
// against the official Success Profiles Strengths Dictionary (GOV.UK) and UK
// graduate careers guidance (Prospects, GraduatesFirst, targetjobs, DWF).
// Success Profiles assesses five elements (Behaviours, Strengths, Ability,
// Experience, Technical); the Strengths Dictionary defines 30+ named strengths
// (e.g. Analytical, Authentic, Catalyst, Disciplined), each assessed on three
// criteria: performance (done at a high level of skill), engagement (feeling
// motivated and enthusiastic doing it), and frequency (done regularly).
// An earlier note here referenced "eight strengths" — that was Fast-Stream-
// scheme framing, not the framework itself, and has been corrected.
export const STRENGTHS_BASED_FORMAT_NOTE =
  'Strengths-based questions (UK Civil Service Success Profiles and many UK graduate employers) probe what the candidate is naturally good at, does regularly, AND genuinely enjoys — assessed on performance, engagement, and frequency together, with assessors watching for authentic enthusiasm in the delivery. Questions sound like "What energises you?" or "What do you find yourself doing without being asked?". These answers cannot be prepared as rehearsed STAR stories and a scripted answer actively hurts — prep means knowing your genuine strengths and being ready to speak about them naturally and briefly, with a real example offered conversationally rather than performed. Coach the candidate to answer with what they actually enjoy ("I love problem-solving through data" beats "I am good at Excel") and to keep answers shorter and more spontaneous than competency answers.'

